#!/usr/bin/env node
/*
 * e6app SFC 编译器 —— Vue 2.6 单文件组件 → Falcon 组件 JS（后续由 qjsc 编译为字节码）
 *
 * 改编自 youdao-dictpen-s7pro-guide 的 falcon_vue_compiler.js（MIT License）
 *   https://github.com/cubelikeplayDaniel/youdao-dictpen-s7pro-guide
 * E6 适配点：
 *   - 默认输出「组件对象」export（E6 契约：框架用注册的 BasePage 包装，
 *     实测 2026-11-02，见 miniapp/glm_usage_app）；--page 保留 S7 Pro 的
 *     setRootComponent 契约以备跨机型使用。
 *   - 只输出 .js（qjsc 编码统一由 lib/build.py 调 build_amr.py 完成）。
 *
 * 用法: node sfc_compiler.js <input.vue> <output.js> [--page] [--rel-path p]
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const compiler = require('vue-template-compiler');
const transpile = require('vue-template-es2015-compiler');
const styler = require('weex-styler');

function parseSFC(content) {
  const templateMatch = content.match(/<template[^>]*>([\s\S]*?)<\/template>/i);
  const scriptMatch = content.match(/<script[^>]*>([\s\S]*?)<\/script>/i);
  const styleMatches = [...content.matchAll(/<style([^>]*)>([\s\S]*?)<\/style>/gi)];

  const template = templateMatch ? templateMatch[1].trim() : '';
  const script = scriptMatch ? scriptMatch[1].trim() : 'export default {};';
  const styles = styleMatches.map(m => ({
    scoped: /scoped/i.test(m[1]),
    content: m[2].trim()
  }));
  return { template, script, styles };
}

function computeScopeId(filePath) {
  const hash = crypto.createHash('sha256').update(filePath).digest('hex').slice(0, 8);
  return `data-v-${hash}`;
}

function compileTemplate(template) {
  if (!template) {
    return { renderCode: 'function render() { return null; }', staticRenderFnsCode: '[]' };
  }

  // Falcon 变换：class 属性 → 字符串数组（与官方应用字节码一致）
  const falconClassModule = {
    transformNode(el) {
      if (el.attrsMap && el.attrsMap.class) {
        const classes = el.attrsMap.class.trim().split(/\s+/).filter(Boolean);
        el.staticClass = JSON.stringify(classes);
      }
    }
  };

  const compiled = compiler.compile(template, {
    preserveWhitespace: false,
    modules: [falconClassModule]
  });

  if (compiled.errors && compiled.errors.length > 0) {
    throw new Error(`模板编译错误:\n${compiled.errors.join('\n')}`);
  }

  // 去掉 with(this)，QuickJS 字节码更小、执行更快
  const renderCode = transpile(`function render() { ${compiled.render} }`);
  const staticRenderFnsCode =
    `[${compiled.staticRenderFns.map(fn => transpile(`function() { ${fn} }`)).join(', ')}]`;
  return { renderCode, staticRenderFnsCode };
}

function compileStyles(styles) {
  return new Promise((resolve, reject) => {
    const allCss = styles.map(s => s.content).join('\n');
    if (!allCss.trim()) return resolve({});
    styler.parse(allCss, (err, res) => {
      if (err) return reject(err);
      resolve(res.jsonStyle || {});
    });
  });
}

async function compileVue(vueFilePath, options = {}) {
  const fileContent = fs.readFileSync(vueFilePath, 'utf-8');
  const relPath = options.relPath || path.basename(vueFilePath);
  const scopeId = options.scopeId || computeScopeId(relPath);

  const { template, script, styles } = parseSFC(fileContent);
  const { renderCode, staticRenderFnsCode } = compileTemplate(template);
  const styleDict = await compileStyles(styles);

  // 剥离 export default，组件对象单独重组
  let scriptBody = script.trim();
  let componentObjExpr = '{}';
  if (/export\s+default\s+/m.test(scriptBody)) {
    const parts = scriptBody.split(/export\s+default\s+/m);
    const preExport = parts[0];
    let postExport = parts[1].trim();
    if (postExport.endsWith(';')) postExport = postExport.slice(0, -1);
    scriptBody = preExport;
    componentObjExpr = postExport;
  }

  const isPage = options.page || false;
  const pageClassName = options.pageClassName || 'FalconPageComponent';

  const jsLines = [];
  jsLines.push('/* Generated by e6app SFC compiler (based on s7pro-guide falcon_vue_compiler, MIT) */');
  if (scriptBody) jsLines.push(scriptBody);
  jsLines.push(`var __falcon_component = ${componentObjExpr};`);
  jsLines.push(`__falcon_component._withStripped = !0;`);
  jsLines.push(`__falcon_component.render = ${renderCode};`);
  jsLines.push(`__falcon_component.staticRenderFns = ${staticRenderFnsCode};`);
  jsLines.push(`__falcon_component._compiled = !0;`);
  jsLines.push(`__falcon_component._scopeId = ${JSON.stringify(scopeId)};`);
  jsLines.push(`__falcon_component.themes = {};`);
  jsLines.push(`__falcon_component.style = Object.assign({}, ${JSON.stringify(styleDict, null, 2)});`);
  jsLines.push(`__falcon_component.__file = ${JSON.stringify(relPath)};`);

  if (isPage) {
    // S7 Pro 契约（E6 上未验证 setRootComponent，默认不用）
    jsLines.push(`
class ${pageClassName} extends $falcon.Page {
  onLoad(options) {
    super.onLoad(options);
    this.setRootComponent(__falcon_component);
  }
}
export default ${pageClassName};
`);
  } else {
    // E6 契约：导出组件对象，框架用 BasePage 包装
    jsLines.push(`export default __falcon_component;`);
  }

  return jsLines.join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length < 2 || args.includes('-h') || args.includes('--help')) {
    console.log('用法: node sfc_compiler.js <input.vue> <output.js> [--page] [--rel-path p]');
    process.exit(args.length < 2 ? 1 : 0);
  }
  const inputFile = path.resolve(args[0]);
  const outputFile = path.resolve(args[1]);
  const isPage = args.includes('--page');
  const relPathIdx = args.indexOf('--rel-path');
  const relPath = relPathIdx !== -1 ? args[relPathIdx + 1] : undefined;

  const compiledJs = await compileVue(inputFile, { page: isPage, relPath });
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, compiledJs, 'utf-8');
  console.log(`SFC: ${inputFile} -> ${outputFile}`);
}

if (require.main === module) {
  main().catch(err => { console.error(err); process.exit(1); });
}

module.exports = { compileVue, parseSFC, compileTemplate, compileStyles };
